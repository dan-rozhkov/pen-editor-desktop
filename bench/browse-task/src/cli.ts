// npm run bench -- [--scenarios lookup,form,booking,shop] [--runs 3]
//   [--policies ultrafast,legacy] [--stack local|prod]
//   [--chat-model deepseek/deepseek-v4.1-flash] [--cascade-model openrouter:google/gemini-2.5-flash]
//   [--prompt task|free|manual|agent] [--no-build]
// --scenarios accepts the groups @live (the 10 real-site scenarios) @om2w (Online-Mind2Web sample), @webvoyager (WebVoyager sample), @wtb and @wtb-e2e (WebTestBench QA apps), e.g. @live or form,@live

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { DESKTOP_DIR, REPORTS_DIR, RESULTS_DIR } from "./paths.ts";
import { SCENARIOS } from "./scenarios.ts";
import { LIVE_SUITE } from "./liveSuite.ts";
import { OM2W_SUITE } from "./om2wSuite.ts";
import { WV_SUITE } from "./webvoyagerSuite.ts";
import { WTB_SUITE, WTB_E2E_SUITE } from "./wtbSuite.ts";
import { startLocalStack, type Stack } from "./stack.ts";
import { runOnce, type PromptStyle } from "./runOnce.ts";
import { writeSummary, runStatsLine } from "./report.ts";

// A live site can open and close a JS dialog (alert/beforeunload) before
// Playwright's own auto-dismiss reaches it; the resulting "No dialog is
// showing" rejection is unhandled inside playwright-core and used to kill the
// whole bench mid-suite (13.10, live10 Luna run at 14/30). Log it, keep going.
process.on("unhandledRejection", (err) => {
  const msg = err instanceof Error ? err.message : String(err);
  if (msg.includes("handleJavaScriptDialog") || msg.includes("No dialog is showing")) {
    console.warn(`[bench] ignored dialog race: ${msg}`);
    return;
  }
  throw err;
});

// Recovery addition (27.10.2026): the run summary also goes to the tracked bench/reports/<run>.md,
// raw outputs (homes, logs, traces, JSON) stay in the ignored results/. BENCH_NO_REPORT=1 disables it.
function summarize(dir: string): string {
  const text = writeSummary(dir);
  if (process.env.BENCH_NO_REPORT !== "1") {
    fs.mkdirSync(REPORTS_DIR, { recursive: true });
    const cfg = path.join(dir, "config.json");
    const head = `<!-- generated by npm run bench; raw outputs: ${path.relative(path.dirname(REPORTS_DIR), dir)} (ignored) -->\n\n` +
      (fs.existsSync(cfg) ? "Config: `" + JSON.stringify(JSON.parse(fs.readFileSync(cfg, "utf8"))) + "`\n\n" : "");
    fs.writeFileSync(path.join(REPORTS_DIR, `${path.basename(dir)}.md`), head + text);
  }
  return text;
}

const PROD_EDITOR = "https://pen-editor.onrender.com/app";

// Default run = the pre-@live scenarios; the live suite is opt-in via `@live`.
const LIVE_IDS = new Set([...LIVE_SUITE, ...OM2W_SUITE, ...WV_SUITE, ...WTB_SUITE, ...WTB_E2E_SUITE].map((s) => s.id));
const DEFAULT_IDS = SCENARIOS.filter((s) => !LIVE_IDS.has(s.id)).map((s) => s.id);

const { values: args } = parseArgs({
  options: {
    scenarios: { type: "string", default: DEFAULT_IDS.join(",") },
    runs: { type: "string", default: "3" },
    policies: { type: "string", default: "ultrafast" },
    stack: { type: "string", default: "local" },
    "chat-model": { type: "string", default: "deepseek/deepseek-v4.1-flash" },
    "cascade-model": { type: "string" },
    prompt: { type: "string", default: "task" },
    "no-build": { type: "boolean", default: false },
    "backend-port": { type: "string", default: "3091" },
    "vite-port": { type: "string", default: "5191" },
    out: { type: "string" },
  },
});

const requested = args.scenarios!
  .split(",")
  .map((x) => x.trim())
  .filter(Boolean)
  .flatMap((x) => {
    if (x === "@live") return LIVE_SUITE.map((s) => s.id);
    if (x === "@om2w") {
      if (!OM2W_SUITE.length) throw new Error("@om2w is empty: data/om2w/sample.json is missing. Run: HF_TOKEN=... npm run om2w:prepare");
      return OM2W_SUITE.map((s) => s.id);
    }
    if (x === "@webvoyager") {
      if (!WV_SUITE.length) throw new Error("@webvoyager is empty: data/webvoyager/sample.json is missing. Run: npm run wv:prepare");
      return WV_SUITE.map((s) => s.id);
    }
    if (x === "@wtb" || x === "@wtb-e2e") {
      const suite = x === "@wtb" ? WTB_SUITE : WTB_E2E_SUITE;
      if (!suite.length) throw new Error(`${x} is empty: no built apps in data/wtb/apps. Run: npm run wtb:prepare`);
      return suite.map((s) => s.id);
    }
    return [x];
  });
const scenarios = requested.map((id) => {
  const s = SCENARIOS.find((x) => x.id === id.trim());
  if (!s) throw new Error(`unknown scenario "${id}" (have: ${SCENARIOS.map((x) => x.id).join(", ")})`);
  return s;
});
const runs = Math.max(1, Number(args.runs) || 1);
const local = args.stack === "local";
const policies = local ? args.policies!.split(",").map((p) => p.trim()) : ["prod"];
for (const p of policies) if (local && p !== "ultrafast" && p !== "legacy") throw new Error(`unknown policy "${p}"`);
const promptStyle = args.prompt as PromptStyle;

const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const outDir = path.resolve(args.out ?? path.join(RESULTS_DIR, stamp));
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "config.json"), JSON.stringify({ ...args, scenarios: scenarios.map((s) => s.id), runs, policies }, null, 2));

if (!args["no-build"]) {
  console.log("building pen-editor-desktop…");
  execFileSync("npm", ["run", "build"], { cwd: DESKTOP_DIR, stdio: "inherit" });
}

let stack: Stack | undefined;
const shutdown = async () => {
  await stack?.stop();
  process.exit(130);
};
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);

console.log(`results → ${outDir}`);
for (const policy of policies) {
  let editorUrl = PROD_EDITOR;
  if (local) {
    console.log(`\n=== policy ${policy}: starting local backend + vite…`);
    stack = await startLocalStack({
      backendPort: Number(args["backend-port"]),
      vitePort: Number(args["vite-port"]),
      policy: policy as "ultrafast" | "legacy",
      chatModel: args["chat-model"]!,
      cascadeModel: args["cascade-model"],
      // --prompt manual = the product default; every other style needs browse_task offered.
      browseMode: promptStyle === "manual" ? "manual" : promptStyle === "agent" ? "agent" : "task",
      outDir,
    });
    editorUrl = stack.editorUrl;
  }
  try {
    // Interleave scenarios within each round so time-of-day drift in
    // provider latency spreads evenly over them.
    for (let i = 0; i < runs; i++) {
      for (const scenario of scenarios) {
        const result = await runOnce({
          scenario,
          policy,
          runIndex: i,
          editorUrl,
          chatModel: args["chat-model"]!,
          promptStyle,
          stack,
          outDir,
        });
        const file = path.join(outDir, `run-${policy}-${scenario.id}-${i + 1}.json`);
        fs.writeFileSync(file, JSON.stringify(result, null, 2));
        console.log(`[${policy}] ${scenario.id} #${i + 1}: ${runStatsLine(result)}`);
        summarize(outDir);
      }
    }
  } finally {
    await stack?.stop();
    stack = undefined;
  }
}

console.log("\n" + summarize(outDir));
console.log(`summary → ${path.join(outDir, "summary.md")}`);
